//! C interface of the homotopy solver for the OpenModelica C runtime.
//!
//! Replaces `nonlinearSolverHomotopy.c`: the C runtime links this crate as a
//! static library and calls the same functions as before, so
//! `nonlinearSystem.c` does not change. The solver itself lives in
//! `homotopy_core`, this crate only translates between the C runtime and it.
//!
//! # Contents when finished
//!
//! - `exports`: the functions of `nonlinearSolverHomotopy.h`, exported with
//!   the C ABI.
//! - `bindings`: the C types (`DATA`, `NONLINEAR_SYSTEM_DATA`,
//!   `NLS_USERDATA`, ...), generated by `bindgen` in a `build.rs` from the
//!   runtime headers.
//! - `model`: implements `homotopy_core`'s model trait on top of
//!   `NONLINEAR_SYSTEM_DATA`: residuals, Jacobian and the strict tearing set.
//! - `runtime`: everything else the solver reads from or writes to the
//!   runtime: start values, solution, relations, statistics, logging and the
//!   hybrd fallback.
//! - A small C file, compiled with the `cc` crate in `build.rs`, that calls
//!   the model under `OMC_TRY_INTERNAL(simulationJumpBuffer)`. A failed
//!   `assert` in the model leaves with `longjmp`, which must not cross Rust
//!   stack frames; the C wrapper catches it and returns an error code instead.
//!
//! All `unsafe` code of the project belongs in this crate.

mod bindings;
mod exports;
mod model;
mod runtime;
